/**
 * A media item as a client is allowed to see it.
 *
 * There is no `storageKey`, `previewKey` or `posterKey` in here, and there never
 * will be: a provider file key names an object directly, so handing one out
 * turns a permission-checked read into a bearer credential with no expiry. Read
 * paths return short-lived signed URLs and nothing else.
 */
export interface MediaView {
  id: Id<"media">;
  eventId: Id<"events">;
  captureId: string;
  state: MediaState;
  mediaType: Doc<"media">["mediaType"];
  fromLibrary: boolean;
  byteSize: number;
  mimeType: string;
  durationSeconds?: number;
  width?: number;
  height?: number;
  uploaderUserId: Id<"users">;
  uploaderDisplayName: string;
  isOwn: boolean;
  createdAt: number;
  capturedAt?: number;
  uploadedAt?: number;
  moderatedAt?: number;
  /** How many open reports. Present only for hosts — see {@link projectMedia}. */
  reportCount?: number;
  flaggedAt?: number;
  /**
   * The **original**. Absent while the item is still processing, when storage is
   * unreachable, and — for a viewer who is neither the submitter nor a host —
   * whenever the client did not confirm it stripped the metadata.
   */
  url?: string;
  urlExpiresAt?: number;
  /** The artefact a gallery renders: downscaled image, or short muted clip. */
  previewUrl?: string;
  previewUrlExpiresAt?: number;
  /** A video's still frame. Absent for photos. */
  posterUrl?: string;
  posterUrlExpiresAt?: number;
}

