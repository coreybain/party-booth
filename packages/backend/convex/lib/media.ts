/**
 * Where an item lands once its bytes are safely stored, given the event's
 * moderation mode.
 *
 * The decision itself is the contract's (`mediaStateAfterProcessing`), so the
 * organiser console, the app and the backend cannot disagree about what
 * `automatic` means. `ai` behaves as `manual` until P1, by the same function.
 */
export async function settleAfterProcessing(
  ctx: MutationCtx,
  media: Doc<"media">,
  event: Doc<"events">,
  now: number,
): Promise<MediaState> {
  const next = mediaStateAfterProcessing(event.moderationMode);
  if (media.state === next) return next;

  // Throws `InvalidTransitionError` on an illegal move rather than writing one.
  mediaStateMachine.assertTransition(media.state, next);

  await ctx.db.patch(media._id, {
    state: next,
    // The slideshow's cursor. `automatic` mode approves here, with no host and
    // no decision row, so this is the only place that timestamp can come from.
    ...(next === "approved" ? { approvedAt: now } : {}),
    updatedAt: now,
  });
  await applyCountChange(ctx, media.eventId, media.state, next, now);

  /*
   * The host pending-queue ping hangs off this, and nothing else.
   *
   * This is the one place in the product where an item *becomes* something a
   * host has to act on — every other route into `pending` is a host's own
   * decision, and telling a host about a queue they just created is noise. The
   * counters are re-read rather than incremented locally because
   * `applyCountChange` is what maintains them and they are exact.
   *
   * `notifyPendingThreshold` swallows every ordinary reason not to send (no
   * devices, opted out, still under the threshold, already pinged this burst),
   * so this line cannot fail an upload. See `lib/notifications.ts`.
   */
  if (next === "pending") {
    const fresh = await ctx.db.get(media.eventId);
    if (fresh) {
      await notifyPendingThreshold(ctx, {
        event: fresh,
        pending: fresh.counts.pending,
        excludeUserId: media.uploaderUserId,
        now,
      });
    }
  }

  return next;
}

