import {
  mediaStateAfterProcessing,
  mediaStateMachine,
  type MediaState,
} from "@partybooth/contracts/media";
import { SIGNED_READ_URL_TTL_SECONDS, type SignedReadUrl } from "@partybooth/contracts/storage";

import type { Doc, Id } from "../_generated/dataModel";
import type { MutationCtx } from "../_generated/server";
import type { ReadCtx } from "./guards";
import { resolveStorageAdapter } from "./storage";

/**
 * The `media` row: creating it, moving it, counting it, and turning it into
 * something a client may see.
 *
 * The one rule that shapes this whole file is **idempotency by
 * `(eventId, captureId)`**. Two things independently announce that an upload
 * happened — the client, when its own request resolves, and the UploadThing
 * route handler, when the provider calls back — and they arrive in either order,
 * more than once each, on a party wifi network that drops packets. Every entry
 * point here therefore looks the row up by that pair first and *reconciles*,
 * rather than inserting and hoping.
 *
 * A concurrent double-insert is prevented by Convex rather than by a lock: two
 * mutations that both read "no row" and both insert are a write conflict, so one
 * commits and the other is re-executed against the committed state, where it
 * finds the row. That is also why nothing here caches a lookup across an `await`
 * that writes.
 */

/* -------------------------------------------------------------------------- */
/* Counters                                                                   */
/* -------------------------------------------------------------------------- */

type CountBucket = "pending" | "approved" | "declined";

/** Which denormalised counter a state belongs to, if any. */
function bucketOf(state: MediaState): CountBucket | null {
  switch (state) {
    case "pending":
    case "approved":
    case "declined":
      return state;
    // `processing` is in `total` but in none of the three: the organiser's
    // pending badge must not blink for a photo that is still uploading.
    // `deleted` is in nothing at all.
    default:
      return null;
  }
}

/** `"none"` is the state a row is in before it exists. */
export type PriorMediaState = MediaState | "none";

function countsIn(state: PriorMediaState): boolean {
  return state !== "none" && state !== "deleted";
}

/**
 * Move the event's counters to match a state change, in the same mutation that
 * made the change.
 *
 * Exact rather than eventually consistent, which is the point of denormalising
 * them at all: the pending badge on the organiser's phone is the thing that
 * tells them whether to keep moderating, and a badge that lags is a badge that
 * gets ignored.
 */
export async function applyCountChange(
  ctx: MutationCtx,
  eventId: Id<"events">,
  from: PriorMediaState,
  to: MediaState,
  now: number,
): Promise<void> {
  if (from === to) return;
  const event = await ctx.db.get(eventId);
  if (!event) return;

  const counts = { ...event.counts };

  const fromBucket = from === "none" ? null : bucketOf(from);
  const toBucket = bucketOf(to);
  if (fromBucket !== null) counts[fromBucket] = Math.max(0, counts[fromBucket] - 1);
  if (toBucket !== null) counts[toBucket] += 1;

  if (!countsIn(from) && countsIn(to)) counts.total += 1;
  if (countsIn(from) && !countsIn(to)) counts.total = Math.max(0, counts.total - 1);

  await ctx.db.patch(eventId, { counts, updatedAt: now });
}

/* -------------------------------------------------------------------------- */
/* Finding and creating                                                       */
/* -------------------------------------------------------------------------- */

export async function findMediaByCapture(
  ctx: ReadCtx,
  eventId: Id<"events">,
  captureId: string,
): Promise<Doc<"media"> | null> {
  return await ctx.db
    .query("media")
    .withIndex("by_event_and_capture", (q) => q.eq("eventId", eventId).eq("captureId", captureId))
    .unique();
}

/**
 * The row a grant describes, creating it in `processing` if it is not there yet.
 *
 * Everything on it comes from the **grant**, never from the caller: the grant is
 * the thing that was permission-checked and size-capped, so it is the only
 * honest source for byte size, type and checksum. A completion callback that
 * disagrees is a mismatch to be refused, not a correction to be applied.
 *
 * Returns `null` when the capture belongs to somebody else. `captureId` is
 * generated by the client and the index is scoped to the event rather than to
 * the person, so two guests at one party can name the same id — and a row is
 * owned by whoever got there first. `requestUploadGrant` already refuses to
 * issue a grant in that case; this is the second lock on the same door, because
 * the failure it prevents is one guest's photo appearing under another guest's
 * name, in their list, withdrawable only by them.
 */
export async function ensureMediaRow(
  ctx: MutationCtx,
  grant: Doc<"uploadGrants">,
  now: number,
): Promise<{ media: Doc<"media">; created: boolean } | null> {
  const existing = await findMediaByCapture(ctx, grant.eventId, grant.captureId);
  if (existing) {
    if (existing.uploaderUserId !== grant.userId) return null;
    return { media: existing, created: false };
  }

  const mediaId = await ctx.db.insert("media", {
    eventId: grant.eventId,
    uploaderUserId: grant.userId,
    captureId: grant.captureId,
    state: "processing",
    mediaType: grant.mediaType,
    grantId: grant._id,
    storageRegion: grant.storageRegion,
    byteSize: grant.byteSize,
    mimeType: grant.mimeType,
    checksum: grant.checksum,
    ...(grant.durationSeconds === undefined ? {} : { durationSeconds: grant.durationSeconds }),
    fromLibrary: grant.fromLibrary,
    ...(grant.sourceMetadataStripped === undefined
      ? {}
      : { sourceMetadataStripped: grant.sourceMetadataStripped }),
    ...(grant.capturedAt === undefined ? {} : { capturedAt: grant.capturedAt }),
    createdAt: now,
    updatedAt: now,
  });

  await applyCountChange(ctx, grant.eventId, "none", "processing", now);

  const media = await ctx.db.get(mediaId);
  if (!media) throw new Error("media row vanished immediately after insert");
  return { media, created: true };
}

