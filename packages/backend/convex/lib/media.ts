/**
 * A media item as a client is allowed to see it.
 *
 * There is no `storageKey`, `previewKey` or `posterKey` in here, and there never
 * will be: a provider file key names an object directly, so handing one out
 * turns a permission-checked read into a bearer credential with no expiry. Read
 * paths return short-lived signed URLs and nothing else.
 */
export interface MediaView {
  id: Id<"media">;
  eventId: Id<"events">;
  captureId: string;
  state: MediaState;
  mediaType: Doc<"media">["mediaType"];
  fromLibrary: boolean;
  byteSize: number;
  mimeType: string;
  durationSeconds?: number;
  width?: number;
  height?: number;
  uploaderUserId: Id<"users">;
  uploaderDisplayName: string;
  isOwn: boolean;
  createdAt: number;
  capturedAt?: number;
  uploadedAt?: number;
  moderatedAt?: number;
  /** Absent while the item is still processing, or when storage is unreachable. */
  url?: string;
  urlExpiresAt?: number;
  previewUrl?: string;
  previewUrlExpiresAt?: number;
}

/**
 * Mint a signed URL, or give up quietly.
 *
 * A read path must not take the whole gallery down because one object is
 * unreachable or because the deployment has no storage credentials yet. The
 * caller renders an item with no image and a status line, which on party night
 * is enormously better than an error screen. The failure is logged once by the
 * adapter, not per item.
 */
async function safeUrl(
  region: Doc<"media">["storageRegion"],
  key: string | undefined,
  expiresInSeconds: number,
): Promise<SignedReadUrl | undefined> {
  if (key === undefined) return undefined;
  try {
    return await resolveStorageAdapter(region).createReadUrl(key, { expiresInSeconds });
  } catch {
    return undefined;
  }
}

export interface ProjectMediaOptions {
  viewerUserId: Id<"users">;
  /** Overrides the default read TTL; see `SIGNED_READ_URL_TTL_SECONDS`. */
  expiresInSeconds?: number | undefined;
}

export async function projectMedia(
  ctx: ReadCtx,
  media: Doc<"media">,
  options: ProjectMediaOptions,
): Promise<MediaView> {
  const ttl = options.expiresInSeconds ?? SIGNED_READ_URL_TTL_SECONDS;
  const uploader = await ctx.db.get(media.uploaderUserId);

  const [original, preview] = await Promise.all([
    safeUrl(media.storageRegion, media.storageKey, ttl),
    safeUrl(media.storageRegion, media.previewKey ?? media.posterKey, ttl),
  ]);

  return {
    id: media._id,
    eventId: media.eventId,
    captureId: media.captureId,
    state: media.state,
    mediaType: media.mediaType,
    fromLibrary: media.fromLibrary,
    byteSize: media.byteSize,
    mimeType: media.mimeType,
    ...(media.durationSeconds === undefined ? {} : { durationSeconds: media.durationSeconds }),
    ...(media.width === undefined ? {} : { width: media.width }),
    ...(media.height === undefined ? {} : { height: media.height }),
    uploaderUserId: media.uploaderUserId,
    uploaderDisplayName: uploader?.displayName ?? "Someone",
    isOwn: media.uploaderUserId === options.viewerUserId,
    createdAt: media.createdAt,
    ...(media.capturedAt === undefined ? {} : { capturedAt: media.capturedAt }),
    ...(media.uploadedAt === undefined ? {} : { uploadedAt: media.uploadedAt }),
    ...(media.moderatedAt === undefined ? {} : { moderatedAt: media.moderatedAt }),
    ...(original === undefined ? {} : { url: original.url, urlExpiresAt: original.expiresAt }),
    ...(preview === undefined
      ? {}
      : { previewUrl: preview.url, previewUrlExpiresAt: preview.expiresAt }),
  };
}
